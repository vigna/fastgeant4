#!/usr/bin/env python3
"""Generates engines/include/CLHEP/Random/G4RngJumpTables.icc: the tables used
to seed xoshiro256++ and MWC192X by jumping, as MixMaxRng::setSeeds does.

A seed s (64 bits: the first two 32-bit seeds) moves a fixed base state by
s * 2^128 steps (xoshiro256++) or s * 2^96 steps (MWC192X), so that distinct
seeds give non-overlapping streams of 2^128 (resp. 2^96) numbers. Entry i of
each table moves by 2^(128 + i) (resp. 2^(96 + i)) steps; seeding applies the
entries of the set bits of s.

- xoshiro256: entry i is x^(2^(128+i)) mod p(x), p the characteristic
  polynomial of the linear engine (from boost-random's xoshiro_base.hpp),
  as 4 little-endian words of coefficients (the format of JUMP[]).
- MWC192X: the state x + y b + c b^2 (b = 2^64) is multiplied modulo
  m = MWC_A2 b^2 - 1 by A = b^-1 = MWC_A2 b at each step; entry i is
  A^(2^(96+i)) mod m in Montgomery form (times 2^192 mod m), as 3
  little-endian words.

The script checks entries 0 and 64 (xoshiro: JUMP, LONG_JUMP) and 0 and 48
(MWC192X: jump(), long_jump()) against the reference constants.
"""

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "engines/include/CLHEP/Random/G4RngJumpTables.icc"
ENTRIES = 64


def words_to_int(ws):
    return sum(w << (64 * i) for i, w in enumerate(ws))


def int_to_words(x, n):
    return [(x >> (64 * i)) & (2**64 - 1) for i in range(n)]


# ---- xoshiro256: arithmetic in F2[x] modulo p(x) of degree 256

XOSHIRO256_CHARPOLY = words_to_int([0x9d116f2bb0f0f001, 0x0280002bcefd1a5e,
                                    0x04b4edcf26259f85, 0x0003c03c3f3ecb19]) | (1 << 256)
XOSHIRO256_JUMP = words_to_int([0x180ec6d33cfd0aba, 0xd5a61266f0c9392c,
                                0xa9582618e03fc9aa, 0x39abdc4529b1661c])
XOSHIRO256_LONG_JUMP = words_to_int([0x76e15d3efefdcbbf, 0xc5004e441c522fb3,
                                     0x77710069854ee241, 0x39109bb02acbe635])


def f2x_mulmod(a, b, p=XOSHIRO256_CHARPOLY, deg=256):
    r = 0
    while b:
        if b & 1:
            r ^= a
        b >>= 1
        a <<= 1
        if (a >> deg) & 1:
            a ^= p
    return r


def xoshiro_table():
    j = 2  # the polynomial x
    for _ in range(128):
        j = f2x_mulmod(j, j)
    assert j == XOSHIRO256_JUMP, "x^(2^128) mod p differs from JUMP"
    table = []
    for _ in range(ENTRIES):
        table.append(j)
        j = f2x_mulmod(j, j)
    assert j == XOSHIRO256_LONG_JUMP, "x^(2^192) mod p differs from LONG_JUMP"
    return table


# ---- MWC192X: arithmetic modulo m = MWC_A2 * 2^128 - 1

MWC_A2 = 0xff4e24dd418f5433
B = 2**64
M = MWC_A2 * B * B - 1
A = MWC_A2 * B  # = b^-1 mod m
MWC_JUMP = 0x702eb67f0959a76b21239e0fbd1ccbb5d323a2a406f64957       # 2^96 steps
MWC_LONG_JUMP = 0xd6c731b43ecad305bceb1c681d8e45f7671d31e08a897fff  # 2^144 steps
R = 2**192


def mwc_table():
    assert (A * B) % M == 1
    assert M % B == B - 1  # m = -1 mod 2^64: Montgomery's m' is 1
    t = pow(A, 2**96, M)
    assert t == MWC_JUMP, "A^(2^96) mod m differs from the jump() constant"
    table = []
    for i in range(ENTRIES):
        if i == 48:
            assert t == MWC_LONG_JUMP, "A^(2^144) mod m differs from long_jump()"
        table.append(t * R % M)  # Montgomery form
        t = t * t % M
    return table


def emit(name, comment, table, n):
    lines = [f"// {comment}", f"static const std::uint64_t {name}[{len(table)}][{n}] = {{"]
    for i, x in enumerate(table):
        ws = ", ".join(f"0x{w:016x}ULL" for w in int_to_words(x, n))
        lines.append(f"  {{ {ws} }},  // {i}")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = ("// Generated by scripts/gen_jump_tables.py: do not edit.\n"
            "// Jump tables for seeding xoshiro256++ and MWC192X (see G4RngEngines.cc).\n\n")
    text += emit("kXoshiro256Jump",
                 "Entry i: x^(2^(128+i)) mod p, the polynomial of a jump by 2^(128+i) steps.",
                 xoshiro_table(), 4)
    text += "\n"
    text += emit("kMwc192xJumpMont",
                 "Entry i: A^(2^(96+i)) mod m in Montgomery form (times 2^192 mod m).",
                 mwc_table(), 3)
    OUT.write_text(text)
    print(f"wrote {OUT} (reference constants verified)")


if __name__ == "__main__":
    sys.exit(main())
