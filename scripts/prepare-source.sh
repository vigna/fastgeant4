#!/bin/bash
# Creates $ROOT/src-<variant>: pristine Geant4 11.4.3 + engines/ overlay + patch
# + a generated CLHEP/Random/G4RngConfig.h.
# Usage: scripts/prepare-source.sh dropin|fast-mixmax|fast-xoshiro256pp|fast-mwc192x
# Run on the build host.
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
source "$repo/hosts/${HOST:-desktop}.env"
variant=${1:?variant}
case $variant in
  dropin) fast= ;;
  fast-mixmax) fast=MixMaxRng ;;
  fast-xoshiro256pp) fast=Xoshiro256ppEngine ;;
  fast-mwc192x) fast=Mwc192xEngine ;;
  *) echo "unknown variant $variant" >&2; exit 1 ;;
esac
tarball=$ROOT/upstream/geant4-v11.4.3.tar.gz
echo "718752c1829cbfcf174f0e539d60ee3f76843b894444e61d2228d66a6887ef6e  $tarball" | sha256sum -c --quiet
src=$ROOT/src-$variant
rm -rf "$src"
mkdir -p "$src"
tar xzf "$tarball" -C "$src" --strip-components=1
clhep=$src/source/externals/clhep
cp "$repo"/engines/include/CLHEP/Random/*.h "$repo"/engines/include/CLHEP/Random/*.icc "$clhep/include/CLHEP/Random/"
cp "$repo"/engines/src/*.cc "$clhep/src/"
patch -s -p1 -d "$src" < "$repo/patches/geant4-11.4.3-rng.patch"
cfg=$clhep/include/CLHEP/Random/G4RngConfig.h
{
  echo "// Generated by scripts/prepare-source.sh for variant $variant."
  echo "#ifndef G4RngConfig_h"
  echo "#define G4RngConfig_h 1"
  if [ -n "$fast" ]; then
    echo "#define G4RNG_FAST $fast"
    echo "#define G4RNG_FAST_NAME \"${variant#fast-}\""
  fi
  echo "#endif"
} > "$cfg"
echo "prepared $src"
